namespace MihuBot.Tests.Molly;

/// <summary>
/// Generates FileSharingVectors.json, the cross-language vectors that <see cref="MollyShareCryptoTests"/> and the Molly
/// client's tests check their implementations against (see MihuBot/Molly/FileSharing.md). Built from .NET primitives
/// and the general <see cref="XAesGcm"/> helper rather than the server's file sharing code. After a format change, run
/// this test with <c>MIHUBOT_WRITE_FILE_SHARING_VECTORS=1</c> to rewrite the file, then copy it to the client's
/// <c>app/src/test/resources/filesharing/</c>.
/// </summary>
public sealed class FileSharingVectorsTests
{
    private const string WriteVariable = "MIHUBOT_WRITE_FILE_SHARING_VECTORS";

    private static readonly byte[] s_prefix = "MihuBot.Molly.Share.v1/"u8.ToArray();

    [Fact]
    public void CheckedInVectors_MatchTheGenerator()
    {
        string generated = Generate();

        if (Environment.GetEnvironmentVariable(WriteVariable) == "1")
        {
            File.WriteAllText(SourcePath(), generated);
        }

        string checkedIn = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Molly", "FileSharingVectors.json")).ReplaceLineEndings("\n");
        Assert.True(generated == checkedIn, $"FileSharingVectors.json is out of date, rerun this test with {WriteVariable}=1 and rebuild.");
    }

    private static string SourcePath([CallerFilePath] string path = "") => Path.Combine(Path.GetDirectoryName(path)!, "FileSharingVectors.json");

    private static string Generate()
    {
        byte[] entry = Det("entry", 16);
        var vectors = new JsonObject { ["description"] = "Generated by FileSharingVectorsTests.cs; see MihuBot/Molly/FileSharing.md" };

        (int A, int B)[] gfPairs = [(0, 0), (1, 0x53), (0x53, 0xCA), (0x57, 0x83), (0xFF, 0xFF), (2, 0x80), (0x1B, 0x9D)];
        vectors["gfMul"] = JsonList(gfPairs.Select(p => JsonList([p.A, p.B, GfMul(p.A, p.B)])));

        byte[] secret = Det("secret", 32);
        const int Threshold = 3, Count = 5;
        byte[][] coefficients = [.. Enumerable.Range(1, Threshold - 1).Select(i => Det($"coefficient{i}", 32))];

        vectors["shamir"] = new JsonObject
        {
            ["secret"] = Hex(secret),
            ["threshold"] = Threshold,
            ["coefficients"] = JsonList(coefficients.Select(c => (JsonNode)Hex(c))),
            ["shares"] = JsonList(Enumerable.Range(1, Count).Select(x => new JsonObject { ["index"] = x, ["value"] = Hex(ShamirShare(secret, coefficients, x)) })),
        };

        byte[] oneSecret = Det("single", 32);
        vectors["shamirThresholdOne"] = new JsonObject { ["secret"] = Hex(oneSecret), ["share"] = Hex(ShamirShare(oneSecret, [], 1)) };

        byte[] key = Det("key", 32);
        byte[] nonce = Det("nonce", 24);

        (string Label, byte[] Plaintext)[] aeadCases = [("data/file", Det("file-prefix", 32)), ("skey/share", Det("share", 101)), ("shared/data-key", Det("data-key-sealed", 81))];

        vectors["aead"] = JsonList(aeadCases
            .Select(v =>
            {
                byte[] subkey = HKDF.DeriveKey(HashAlgorithmName.SHA512, key, 32, salt: [], info: [.. s_prefix, .. Ascii(v.Label), .. entry]);

                return new JsonObject
                {
                    ["key"] = Hex(key),
                    ["entry"] = Hex(entry),
                    ["label"] = v.Label,
                    ["subkey"] = Hex(subkey),
                    ["nonce"] = Hex(nonce),
                    ["plaintext"] = Hex(v.Plaintext),
                    ["ciphertext"] = Hex(XAesEncrypt(subkey, nonce, v.Plaintext, [.. s_prefix, .. Ascii(v.Label), 0, .. entry])),
                };
            }));

        byte[] identityPrivate = Det("identity-private", 32);
        byte[] transportPrivate = Det("transport-private", 32);
        using X25519DiffieHellman identity = X25519DiffieHellman.ImportPrivateKey(identityPrivate);
        using X25519DiffieHellman transport = X25519DiffieHellman.ImportPrivateKey(transportPrivate);
        byte[] identityKey = [0x05, .. identity.ExportPublicKey()];
        byte[] transportPublic = transport.ExportPublicKey();
        byte[] recipientKeyId = SHA512.HashData(transportPublic)[..16];
        byte[] ephemeral = Det("ephemeral", 32);
        byte[] requestNonce = Det("request-nonce", 16);
        byte[] aci = Det("aci", 16);
        const string Action = "share-get";
        byte[] dh = new byte[32];
        identity.DeriveRawSecretAgreement(transportPublic, dh);
        byte[] authKey = HKDF.DeriveKey(HashAlgorithmName.SHA512, dh, 64, salt: [], info: [.. "MihuBot.Molly.Share.Auth.v1"u8, .. recipientKeyId, .. ephemeral, .. requestNonce, .. Ascii(Action)]);
        byte[] macInput = [.. aci, .. identityKey];
        byte[] mac = HMACSHA512.HashData(authKey, macInput);

        vectors["requestAuth"] = new JsonObject
        {
            ["identityPrivateKey"] = Hex(identityPrivate),
            ["identityKey"] = Hex(identityKey),
            ["transportPrivateKey"] = Hex(transportPrivate),
            ["transportPublicKey"] = Hex(transportPublic),
            ["recipientKeyId"] = Hex(recipientKeyId),
            ["clientEphemeralPublicKey"] = Hex(ephemeral),
            ["requestNonce"] = Hex(requestNonce),
            ["action"] = Action,
            ["aci"] = Hex(aci),
            ["dh"] = Hex(dh),
            ["authKey"] = Hex(authKey),
            ["mac"] = Hex(mac),
        };

        byte[] ownerAci = Det("owner-aci", 16), ownerKey = [0x05, .. Det("owner-key", 32)];
        byte[] recipientAci = Det("recipient-aci", 16), recipientKey = [0x05, .. Det("recipient-key", 32)];
        byte[] trusteeAci = Det("trustee-aci", 16), trusteeKey = [0x05, .. Det("trustee-key", 32)];

        byte[] shareT = [1, .. Det("share-value", 32), .. entry, .. trusteeAci, .. trusteeKey, 2, 3, 5];
        byte[][] objects = [.. ((int[])[52972, 121, 4145, 65580, 81]).Select((length, i) => Det($"object{i}", length))];
        const int Revision = 3;
        byte[] descriptor = [1, .. entry, .. U32(Revision), .. ownerAci, .. ownerKey, .. recipientAci, .. recipientKey, 32, .. objects.SelectMany(o => (byte[])[.. U32(o.Length), .. SHA512.HashData(o)])];

        byte[] instructionsText = Encoding.UTF8.GetBytes("Call me first: 555-0100 \u2713");
        byte[] instructions = [.. U16(instructionsText.Length), .. instructionsText, .. new byte[1024 - instructionsText.Length]];
        byte[] content = "hello, file sharing"u8.ToArray();
        byte[] filePlain = [.. U32(content.Length), .. content, .. new byte[65536 - content.Length]];
        byte[] name = "note.txt"u8.ToArray(), mime = "text/plain"u8.ToArray(), message = Encoding.UTF8.GetBytes("For B \u2014 thanks");
        byte[] metadata = [2, .. U16(name.Length), .. name, .. U16(mime.Length), .. mime, .. U32(content.Length), .. U16(message.Length), .. message];
        metadata = [.. metadata, .. new byte[4096 - metadata.Length]];

        const long StartedAt = 1_800_000_000;
        byte[] shareTSenc = Det("share-t-senc", 141);
        byte[] sealedValue = Det("sealed", 1395);
        byte[] databaseKey = Det("database-key", 32);
        byte[] serverKey = HKDF.DeriveKey(HashAlgorithmName.SHA512, databaseKey, 64, salt: [], info: [.. s_prefix, .. "server-key"u8]);
        byte[] partyInput = [.. s_prefix, .. "party"u8, .. trusteeAci, .. trusteeKey];

        vectors["codec"] = new JsonObject
        {
            ["entry"] = Hex(entry),
            ["ownerAci"] = Hex(ownerAci),
            ["ownerKey"] = Hex(ownerKey),
            ["recipientAci"] = Hex(recipientAci),
            ["recipientKey"] = Hex(recipientKey),
            ["trusteeAci"] = Hex(trusteeAci),
            ["trusteeKey"] = Hex(trusteeKey),
            ["shareT"] = new JsonObject { ["value"] = Hex(Det("share-value", 32)), ["index"] = 2, ["threshold"] = 3, ["count"] = 5, ["encoded"] = Hex(shareT) },
            ["descriptor"] = new JsonObject
            {
                ["revision"] = Revision,
                ["objectLengths"] = JsonList(objects.Select(o => (JsonNode)o.Length)),
                ["objectSha512"] = JsonList(objects.Select(o => (JsonNode)Hex(SHA512.HashData(o)))),
                ["encoded"] = Hex(descriptor),
            },
            ["instructions"] = new JsonObject { ["text"] = Encoding.UTF8.GetString(instructionsText), ["sha512"] = Hex(SHA512.HashData(instructions)) },
            ["file"] = new JsonObject { ["content"] = Hex(content), ["sha512"] = Hex(SHA512.HashData(filePlain)) },
            ["metadata"] = new JsonObject
            {
                ["kind"] = 2,
                ["name"] = Encoding.UTF8.GetString(name),
                ["mime"] = Encoding.UTF8.GetString(mime),
                ["contentLength"] = content.Length,
                ["message"] = Encoding.UTF8.GetString(message),
                ["sha512"] = Hex(SHA512.HashData(metadata)),
            },
            ["grantMessage"] = Hex([.. s_prefix, .. "grant\0"u8, .. descriptor]),
            ["approvalMessage"] = new JsonObject
            {
                ["startedAt"] = StartedAt,
                ["shareTSenc"] = Hex(shareTSenc),
                ["encoded"] = Hex([.. s_prefix, .. "approval\0"u8, .. entry, .. I64(StartedAt), .. trusteeAci, .. trusteeKey, .. SHA512.HashData(shareTSenc)]),
            },
            ["trusteeSealedMessage"] = new JsonObject
            {
                ["sealedSha512"] = Hex(SHA512.HashData(sealedValue)),
                ["encoded"] = Hex([.. s_prefix, .. "trustee-sealed\0"u8, .. entry, .. ownerAci, .. ownerKey, .. trusteeAci, .. trusteeKey, .. SHA512.HashData(sealedValue)]),
            },
            ["partyHash"] = new JsonObject
            {
                ["databaseKey"] = Hex(databaseKey),
                ["serverKey"] = Hex(serverKey),
                ["hash"] = Hex(HMACSHA512.HashData(serverKey, partyInput)),
            },
        };

        var options = new JsonSerializerOptions { WriteIndented = true, IndentSize = 2, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
        return vectors.ToJsonString(options) + "\n";
    }

    /// <summary>Deterministic test bytes: <c>SHA-512(label || counter)</c> blocks.</summary>
    private static byte[] Det(string label, int length)
    {
        var output = new List<byte>(length + 64);

        for (int counter = 0; output.Count < length; counter++)
        {
            output.AddRange(SHA512.HashData([.. Ascii(label), .. U32(counter)]));
        }

        return [.. output.Take(length)];
    }

    /// <summary>XAES-256-GCM with an explicit nonce, as <c>nonce || ciphertext || tag</c>.</summary>
    private static byte[] XAesEncrypt(byte[] key, byte[] nonce, byte[] plaintext, byte[] associatedData)
    {
        using var aead = new XAesGcm(key);
        byte[] ciphertext = new byte[plaintext.Length];
        byte[] tag = new byte[XAesGcm.TagSizeInBytes];
        aead.Encrypt(nonce, plaintext, ciphertext, tag, associatedData);
        return [.. nonce, .. ciphertext, .. tag];
    }

    private static int GfMul(int a, int b)
    {
        int result = 0;

        for (int i = 0; i < 8; i++)
        {
            if ((b & 1) != 0)
            {
                result ^= a;
            }

            bool carry = (a & 0x80) != 0;
            a = (a << 1) & 0xFF;

            if (carry)
            {
                a ^= 0x1B;
            }

            b >>= 1;
        }

        return result;
    }

    /// <summary><c>f(x) = s + a1 x + ...</c> per byte, by Horner's method from the highest coefficient.</summary>
    private static byte[] ShamirShare(byte[] secret, byte[][] coefficients, int x)
    {
        byte[] share = new byte[secret.Length];

        for (int i = 0; i < secret.Length; i++)
        {
            int y = 0;

            foreach (byte[] coefficient in coefficients.Reverse())
            {
                y = GfMul(y, x) ^ coefficient[i];
            }

            share[i] = (byte)(GfMul(y, x) ^ secret[i]);
        }

        return share;
    }

    private static JsonArray JsonList<T>(IEnumerable<T> items) where T : JsonNode => new(items.ToArray<JsonNode?>());

    private static JsonArray JsonList(int[] items) => new(items.Select(i => (JsonNode?)i).ToArray());

    private static string Hex(byte[] value) => Convert.ToHexStringLower(value);

    private static byte[] Ascii(string value) => Encoding.ASCII.GetBytes(value);

    private static byte[] U16(int value)
    {
        byte[] bytes = new byte[2];
        BinaryPrimitives.WriteUInt16BigEndian(bytes, checked((ushort)value));
        return bytes;
    }

    private static byte[] U32(int value)
    {
        byte[] bytes = new byte[4];
        BinaryPrimitives.WriteUInt32BigEndian(bytes, checked((uint)value));
        return bytes;
    }

    private static byte[] I64(long value)
    {
        byte[] bytes = new byte[8];
        BinaryPrimitives.WriteInt64BigEndian(bytes, value);
        return bytes;
    }
}
